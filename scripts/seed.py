def generate_password() -> str:
    return "".join(secrets.choice(PASSWORD_ALPHABET) for _ in range(PASSWORD_LENGTH))


def create_if_missing(db, spec, password, credential_lines, label=""):
    existing = db.query(User).filter(User.username == spec["username"]).first()
    if existing:
        print(f"skip (already exists, password unchanged): {spec['username']} ({spec['role'].value})")
        return

    user = User(
        username=spec["username"],
        hashed_password=hash_password(password),
        full_name=spec["full_name"],
        role=spec["role"],
        email=spec["email"],
    )
    db.add(user)
    db.commit()
    print(f"created{label}: {spec['username']} ({spec['role'].value}) - email: {spec['email']}")
    print(f"  password: {password}")
    credential_lines.append(
        f"- **{spec['full_name']}**{label} ({spec['role'].value}) "
        f"— username: `{spec['username']}`, email: `{spec['email']}`, "
        f"password: `{password}`"
    )


def seed_real_users(db, credential_lines):
    for spec in REAL_USERS:
        password = os.getenv(spec["env_var"]) or generate_password()
        create_if_missing(db, spec, password, credential_lines)


def seed_demo_users(db, credential_lines):
    if os.getenv("ENVIRONMENT") == "production":
        print("Refusing to create demo accounts: ENVIRONMENT=production is set.")
        sys.exit(1)

    for spec in DEMO_USERS:
        create_if_missing(db, spec, DEMO_PASSWORD, credential_lines, label=" (demo, local only)")


def write_credentials(credential_lines):
    if not credential_lines:
        print("\nNo new accounts created - all already existed, no new passwords to show.")
        return

    is_new_file = not os.path.exists(CREDENTIALS_PATH)
    with open(CREDENTIALS_PATH, "a") as f:
        if is_new_file:
            f.write("# CampusPass credentials (dev-only, never commit)\n\n")
            f.write(
                "Generated by `python -m scripts.seed`. This file is gitignored - "
                "do not remove it from .gitignore or commit it.\n\n"
            )
        f.write("\n".join(credential_lines) + "\n")

    print(f"\nNew credentials written to {CREDENTIALS_PATH} (gitignored, never commit this file).")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--demo",
        action="store_true",
        help=(
            "Also create local-only demo accounts (student1/teacher1/hod1, "
            "password123). Refuses to run when ENVIRONMENT=production."
        ),
    )
    args = parser.parse_args()

    Base.metadata.create_all(bind=engine)
    db = SessionLocal()
    credential_lines = []
    try:
        seed_real_users(db, credential_lines)
        if args.demo:
            seed_demo_users(db, credential_lines)
    finally:
        db.close()

    write_credentials(credential_lines)


if __name__ == "__main__":
    main()
