// Decodes a JWT's payload WITHOUT verifying its signature. Never trust this
// for anything security-sensitive — it's only for reading claims (like an
// expiry) to display to the user. The server is the source of truth for
// validity.
export default function decodeJwtPayload(token) {
  try {
    const base64Url = token.split(".")[1];
    const base64 = base64Url.replace(/-/g, "+").replace(/_/g, "/");
    const json = decodeURIComponent(
      atob(base64)
        .split("")
        .map((c) => "%" + c.charCodeAt(0).toString(16).padStart(2, "0"))
        .join("")
    );
    return JSON.parse(json);
  } catch {
    return null;
  }
}
